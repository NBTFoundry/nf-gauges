"""Writes a C file holding a file's bytes or a string, rewritten only when its
contents change (so make rebuilds only then).

  embed.py bytes <input> <symbol> <output.c>   unsigned char <symbol>[], <symbol>_size
  embed.py text <value> <symbol> <output.c>    const char <symbol>[]
"""

import sys
from pathlib import Path


def write_if_changed(path: Path, text: str) -> None:
    if path.exists() and path.read_text() == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text)
    tmp.replace(path)


def main() -> int:
    if len(sys.argv) != 5 or sys.argv[1] not in ("bytes", "text"):
        print(__doc__, file=sys.stderr)
        return 2
    kind, source, symbol, output = sys.argv[1:]
    head = "/* Generated by tools/embed.py: do not edit. */\n"
    if kind == "bytes":
        data = Path(source).read_bytes()
        lines = [", ".join(str(b) for b in data[i : i + 24]) for i in range(0, len(data), 24)]
        body = ",\n".join(lines)
        text = (f"{head}const unsigned char {symbol}[] = {{\n{body}\n}};\n"
                f"const unsigned int {symbol}_size = {len(data)}u;\n")
    else:
        escaped = source.replace("\\", "\\\\").replace('"', '\\"')
        text = f'{head}const char {symbol}[] = "{escaped}";\n'
    write_if_changed(Path(output), text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
